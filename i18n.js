let currentLang = 'en';

function t(key) {
  if (I18N_DATA[currentLang] && I18N_DATA[currentLang][key]) {
    return I18N_DATA[currentLang][key];
  }
  return (I18N_DATA['en'] && I18N_DATA['en'][key]) || key;
}

function setAppLanguage(lang) {
  if (!['en', 'hi', 'te'].includes(lang)) {
    lang = 'en';
  }
  currentLang = lang;
  
  // Update all DOM elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = t(key);
    if (translation) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translation;
      } else {
        el.textContent = translation;
      }
    }
  });

  // Update elements with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translation = t(key);
    if (translation) {
      el.placeholder = translation;
    }
  });

  // Update language select dropdowns
  const langSelect = document.getElementById('langSelect');
  if (langSelect && langSelect.value !== lang) {
    langSelect.value = lang;
  }

  // Dispatch custom event for listeners
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}
